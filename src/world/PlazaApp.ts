/** An open place of the version 2 (lot V5, journal Passe V5): one of the three squares of Plazas.ts, walked across by the hero (arrows or
 *  WASD), its people standing at their spots and the crowd walking between its points, seen by a camera that follows the hero across the
 *  surface and leans toward where it walks (a framing graph for an open space: the pose a smooth function of the hero's place, no cut).
 *  The town's renderer (materials, lights, sky, moon or sun, shadow, puddle reflection, post chain), the day state of the page (`time`).
 *  The people: the production cast's approved baked sheets placed by role (AV-14: the guards, the townsfolk and their V1 variants, the porter,
 *  the hero), and for a role without a sheet a sprite generated by the code, marked provisional (`provisional`). The visibility bake of the
 *  district's rule (journal Passe VP1, src/world/PlazaVisibility.ts; `?vis=0` without it), the town's weather (`rain`, `snow`, `storm`,
 *  `wind`); the GPU measure is a local task. */

export interface PlazaOptions {
  canvas: HTMLCanvasElement; params: URLSearchParams; onProgress: (label: string, f: number) => void; kind: PlazaKind; time: DayTime | null; people: string[]; crowd: number;
  /** the place the hero arrives from (journal Passe VP5): they stand at the way in from it, facing the square; null = the square's mouth */
  arriveFrom?: string | null;
}

/** the roles a square shows, and the archetype standing for each (a baked sheet replaces the archetype when one is approved) */
const ROLE_ARCHETYPE: Record<string, string> = { guardA: 'guardA', guardB: 'guardB', hooded: 'hooded', porter: 'porter' };
/** the people of the version 2 without a baked sheet: generated, provisional (the list of characters to bake: journal Passe V5) */
export const PROVISIONAL = ['odo', 'anwen', 'hilde', 'corvin', 'pip', 'lio', 'orla', 'vessa', 'marek', 'ilse', 'cassius', 'drill', 'bard'];
/** the key light of a square by the look (journal Passe VP1, « proposé »): a square is closed on three sides (the north and the two rows), open
 *  to the south where the camera stands, so a low light can only reach its floor through that open side: the moon and the sun come from the
 *  south, a little to one side (the north facades lit, the shadows falling away from the camera, the floor never swallowed by a row's
 *  shadow); the morning from the south-east, the end of day low and golden from the south-west (its long shadows), midday high. [KO] the
 *  first build's moon, from the north-west at 33 deg: the Colosseum's wall (13 m) shadowed the whole forecourt at night. */
export function plazaKeyLight(look: DayLook | null, t: DayTime | null, kind: PlazaKind = 'festival'): THREE.Vector3 {
  // (midday a little lower and from the side, journal Passe VP6, tenth critique: « flat daylight, no building throws a shadow across the square »)
  // (journal Passe VP7, the plan's « un soleil choisi par place »: at midday the forecourt's sun rakes the arena's front from the east, a row's
  // shadow across its floor; the training ground's comes from the west over its dummy's ring, the ring in the light)
  const MIDDAY: Record<PlazaKind, [number, number]> = { forecourt: [62, 42], training: [-35, 46], festival: [32, 50] };
  const [az, el] = !look || !t ? [-25, 32] : t === 'morning' ? [40, 22] : t === 'midday' ? MIDDAY[kind] : [-55, 15];
  const a = THREE.MathUtils.degToRad(az), e = THREE.MathUtils.degToRad(el);
  return new THREE.Vector3(Math.sin(a) * Math.cos(e), Math.sin(e), Math.cos(a) * Math.cos(e)).normalize();
}
/** the haze of the squares (journal Passe VP6): where it starts (m) and its density against the day state's (DEV `plazafog=start,density`) */
const PLAZA_FOG = { start: 12, density: 1.6 };
/** by day (journal Passe VP8, the audit: « a milky haze washes out the gate, the pavilions and the tower bases only about 20 m away »): from
 *  16 m, a quarter over the day state's density (from 20 m at its own, the fourth critique preferred VP6's air: « hazier, bluer midday »,
 *  « sun haze for depth »); the night keeps the haze above */
const PLAZA_FOG_DAY = { start: 16, density: 1.25 };
/** the squares' depth of field (journal Passe VP6): its range (m) around the hero's depth; the district's 16 m blurs only its far city, and a
 *  square stands whole within 13-40 m of the camera (DEV `plazadof=range,far`) */
// (the near blur at 0.45 since journal Passe VP7, iteration 3: the near edge is the frames' foreground, « smeared by depth of field » at full)
const PLAZA_DOF = { range: 12, far: 0.5, near: 0.45 };
/** the squares' daylight (journal Passe VP6): the sun's gain and the sky's and ground's fill against the day state's */
// (since journal Passe VP8 the sun a little lower and the sky's fill higher: « every cast shadow, opening and window pane flattens to one
// textureless navy at about 21/255 », « canvas near clipping (95th percentile 243) »; before, key 1.18 and fill 0.86; the ground's warm
// bounce raised with the sky's, 1.5, the shadows went « grey and brown », the fourth critique: the sky's alone, the shadows blue again)
const PLAZA_SUN = { key: 1.05, sky: 1.5, ground: 0.95, sat: 1.0 };
/** the widest frame the squares' visibility bake covers (src/world/PlazaVisibility.ts) */
export const PLAZA_FRAME = 2.4;
/** the camera of a square for a hero at (x, z) (the framing of the zone they stand in, src/world/PlazaCamera.ts: journal Passe VP7), or for a
 *  focus point at distance `dist` (a dialogue, a cutscene's look): the page eases toward it */
export function plazaCamPose(kind: PlazaKind, px: number, pz: number, dist: number | null): CamPose {
  return dist !== null ? lookPose(kind, px, pz, dist) : framingPose(framingAt(kind, px, pz), px, pz);
}
/** the crowd by the moment of the day (journal Passe VP7, « proposé »): how many walk together, how long they linger at a point (s: a base and
 *  a step, five steps by walker) */
const CROWD: Record<PlazaPeriod, { size: number; linger: [number, number] }> = {
  morning: { size: 1, linger: [0.8, 0.5] }, midday: { size: 3, linger: [7, 1.6] }, afternoon: { size: 2, linger: [2, 0.8] }, night: { size: 2, linger: [6, 1.5] },
};
/** the characters' scale in the squares: B's (journal Passe VP1) */
const CHAR_SCALE = 1.12;
/** the squares' moon: below the first build's (journal Passe VP1, third critique: the moonlit plaster outshone the lamps, the night's
 *  brightest quarter lilac where the district's is amber; 0.8 x warmed it half way); 0.68 x from VP1 to VP7's fourth iteration, 0.8 x since
 *  its fifth, the lamp posts gone from the floor (« the night floors go warm sepia instead of indigo ») */
const NIGHT_MOON = new THREE.Color(0.27, 0.37, 0.58).multiplyScalar(0.8);

