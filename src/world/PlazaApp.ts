import * as THREE from 'three';
import { MaterialLibrary } from '../materials/MaterialLibrary';
import { defaultPainters } from '../materials/PainterPool';
import { PostFX } from '../atmosphere/PostFX';
import { MoonShadow, PlanarReflection, LAYER_NOREFLECT } from '../atmosphere/ShadowAndReflection';
import { LightRig, type LightSource } from '../atmosphere/LightRig';
import { ParticleSystem } from '../atmosphere/Particles';
import { U } from '../atmosphere/SceneUniforms';
import { buildSky } from '../atmosphere/Sky';
import { LOOKS, type DayLook, type DayTime } from '../atmosphere/DayState';
import { applyPose, type CamPose } from '../app/CameraRig';
import { FrameCap, parseFrameCap } from '../app/FrameCap';
import { PerfMonitor } from '../debug/PerfMonitor';
import { SpriteAtlas } from '../characters/SpriteAtlas';
import { SpriteRenderer, type Actor } from '../characters/SpriteRenderer';
import { crowdVariants, GUARD_A, GUARD_B, HOODED, PLAYER, PORTER, type CharSpec } from '../characters/SpriteGenerator';
import { loadProductionCast, type CastMember } from '../characters/BakedCast';
import { variantOf } from '../characters/Variants';
import { fiveViewFacing } from '../characters/ActorSystem';
import type { Anim, Dir } from '../characters/SpriteGenerator';
import { buildPlaza, walkTo, type PlazaBuild, type PlazaKind } from './Plazas';

/** An open place of the version 2 (lot V5, journal Passe V5): one of the three squares of Plazas.ts, walked across by the hero (arrows or
 *  WASD), its people standing at their spots and the crowd walking between its points, seen by a camera that follows the hero across the
 *  surface and leans toward where it walks (a framing graph for an open space: the pose a smooth function of the hero's place, no cut).
 *  The town's renderer (materials, lights, sky, moon or sun, shadow, puddle reflection, post chain), the day state of the page (`time`).
 *  The people: the production cast's approved baked sheets placed by role (AV-14: the guards, the townsfolk and their V1 variants, the porter,
 *  the hooded stranger, the hero), and for a role without a sheet a sprite generated by the code, marked provisional (`provisional`). No
 *  visibility bake: a square is small (its triangles counted in `snapshot`); the GPU measure and the bake are local tasks. */

export interface PlazaOptions { canvas: HTMLCanvasElement; params: URLSearchParams; onProgress: (label: string, f: number) => void; kind: PlazaKind; time: DayTime | null; people: string[]; crowd: number }

/** the roles a square shows, and the archetype standing for each (a baked sheet replaces the archetype when one is approved) */
const ROLE_ARCHETYPE: Record<string, string> = { guardA: 'guardA', guardB: 'guardB', hooded: 'hooded', porter: 'porter' };
/** the people of the version 2 without a baked sheet: generated, provisional (the list of characters to bake: journal Passe V5) */
export const PROVISIONAL = ['odo', 'anwen', 'hilde', 'corvin', 'pip', 'lio', 'orla', 'vessa', 'marek', 'ilse', 'cassius', 'drill', 'bard'];
const MOON_DIR = new THREE.Vector3(-0.35, 0.55, -0.76).normalize();
const NIGHT_MOON = new THREE.Color(0.27, 0.37, 0.58);

export class PlazaApp {
  readonly renderer: THREE.WebGLRenderer;
  readonly scene = new THREE.Scene();
  readonly camera = new THREE.PerspectiveCamera(40, 16 / 9, 0.3, 700);
  readonly post: PostFX;
  readonly shadow = new MoonShadow(2048);
  readonly reflection = new PlanarReflection();
  readonly lights = new LightRig();
  readonly frameCap = new FrameCap();
  readonly perf = new PerfMonitor();
  readonly look: DayLook | null;
  readonly keyDir: THREE.Vector3;
  lib!: MaterialLibrary;
  place!: PlazaBuild;
  particles!: ParticleSystem;
  atlas!: SpriteAtlas;
  sprites!: SpriteRenderer;
  player!: Actor;
  readonly people: Actor[] = [];
  /** who stands at which spot (actor -> person id) */
  readonly who = new Map<Actor, string>();
  time = 0;
  frozen: number | null = null;
  frameCount = 0;
  buildMs = 0;
  keys = new Set<string>();
  private pose: CamPose = { yaw: 0, pitch: THREE.MathUtils.degToRad(22), dist: 17, fov: 40, shift: 0, tx: 0, ty: 1.2, tz: -6 };
  private lastT = performance.now();
  private cast: Map<string, CastMember> | null = null;

  constructor(private opts: PlazaOptions) {
    this.renderer = new THREE.WebGLRenderer({ canvas: opts.canvas, antialias: false, powerPreference: 'high-performance', stencil: false, alpha: false });
    this.renderer.autoClear = false;
    this.renderer.info.autoReset = false;
    this.perf.attach(this.renderer.getContext() as WebGL2RenderingContext);
    this.post = new PostFX(this.renderer);
    const q = opts.params;
    if (q.has('gpuprof')) this.perf.gpu.enabled = true;
    this.frameCap.mode = parseFrameCap(q.get('fps')) ?? { kind: 'adaptive', fps: 60 };
    if (q.has('freeze')) this.frozen = parseFloat(q.get('freeze')!);
    this.scene.add(this.camera);
    this.camera.layers.enable(LAYER_NOREFLECT);
    this.look = opts.time ? LOOKS[opts.time] : null;
    this.keyDir = this.look ? this.look.sunDir.clone() : MOON_DIR.clone();
    this.scene.add(buildSky(this.look?.sky ?? null));
    this.reflection.clipY = 0;
    U.uMoonDir.value.copy(this.keyDir);
    U.uMoonCol.value.copy(NIGHT_MOON);
    if (this.look) {
      const L = this.look;
      U.uMoonCol.value.copy(L.sunCol);
      U.uSkyAmb.value.copy(L.skyAmb); U.uGroundAmb.value.copy(L.groundAmb); U.uFillCol.value.copy(L.fillCol);
      U.uFogColor.value.copy(L.fogColor); U.uSkyZenith.value.copy(L.skyZenith); U.uCityGlow.value.setRGB(0, 0, 0);
      U.uFogDensity.value = L.fogDensity; U.uMist.value = L.mist; U.uWet.value = L.wet;
      Object.assign(this.post.params, L.post, { shadowTint: L.post.shadowTint!.clone(), highlightTint: L.post.highlightTint!.clone() });
    }
    window.addEventListener('resize', () => this.resize());
    window.addEventListener('keydown', (e) => { if (!e.metaKey && !e.ctrlKey && !e.altKey && !(e.target instanceof HTMLInputElement)) this.keys.add(e.key.toLowerCase()); });
    window.addEventListener('keyup', (e) => this.keys.delete(e.key.toLowerCase()));
    window.addEventListener('blur', () => this.keys.clear());
  }

  async init(): Promise<void> {
    const pq = this.opts.params.get('painters');
    const painters = pq === 'main' ? 0 : pq !== null && /^\d+$/.test(pq) ? +pq : defaultPainters();
    this.frameCap.probe();
    this.lib = await MaterialLibrary.build(this.renderer, this.opts.onProgress, painters);
    if (this.look) { this.lib.slot.glow.uniforms.uEmissive.value = this.look.glowEmissive; this.lib.slot.shop.uniforms.uEmissive.value = this.look.shopEmissive; this.lib.slot.roof.uniforms.uBase.value.copy(this.look.roofTint); }
    this.frameCap.endProbe();
    this.opts.onProgress(this.opts.kind, 0.95);
    await new Promise((r) => setTimeout(r, 0));
    const t0 = performance.now();
    this.place = buildPlaza(this.lib, this.opts.kind, 1842, { day: !!this.look });
    this.buildMs = performance.now() - t0;
    this.scene.add(this.place.group);
    for (const l of this.place.lights) {
      const s: LightSource = this.lights.add(l, 'static', Math.abs(Math.sin(l.pos[0] * 12.9 + l.pos[2] * 78.2)));
      // by day only the fires burn (J4): lanterns and windows unlit
      if (this.look && !l.day) s.scale = s.targetScale = 0;
    }
    this.particles = new ParticleSystem(this.lib);
    this.particles.setEmitters(this.place.emitters);
    this.scene.add(this.particles.group);
    // the cast: the approved baked sheets (the hero, the guards, the townsfolk and their variants, the porter, the hooded); ?cast=generated
    // keeps every role generated
    this.opts.onProgress('people', 0.97);
    const castMode = this.opts.params.get('cast'), cast = castMode === 'generated' ? null : await loadProductionCast(false, 'approved');
    this.cast = cast?.cast ?? null;
    const prov = crowdVariants(7351, PROVISIONAL.length).map((s, i): CharSpec => ({ ...s, id: `prov-${PROVISIONAL[i]}` }));
    this.atlas = SpriteAtlas.build([PLAYER, GUARD_A, GUARD_B, HOODED, PORTER, ...crowdVariants(1842, 5), ...prov], cast?.sheets ?? [], this.renderer.capabilities.maxTextureSize);
    this.sprites = new SpriteRenderer(this.atlas, 64);
    this.sprites.setEdgeMode('dark');
    this.scene.add(this.sprites.group);
    this.player = this.actor('player', 'player', 0, 1.5, 1);
    this.player.dir = 'up'; this.player.facing = 'up';
    for (const id of this.opts.people) {
      const at = this.place.spots[id]; if (!at) continue;
      const a = this.actor(ROLE_ARCHETYPE[id] ?? `prov-${id}`, 'person', at[0], at[1], 100 + this.people.length);
      this.people.push(a); this.who.set(a, id);
    }
    // the crowd: the five townsfolk in turn (their V1 variants by id), walking between the square's points
    for (let i = 0; i < this.opts.crowd; i++) {
      const p = this.place.wander[i % this.place.wander.length];
      const a = this.actor(`crowd${i % 5}`, 'crowd', p[0], p[1], 200 + i);
      a.behaviour = { kind: 'wander', seed: 31 * i + 7, idx: (i * 3) % this.place.wander.length, wait: (i % 4) * 0.7 };
      this.people.push(a);
    }
    this.resize();
    this.lights.update(this.time, 0, this.camera);
    this.shadow.update(this.renderer, this.scene, new THREE.Vector3(0, 2, -7), this.keyDir, 28, 28);
    const prev = this.renderer.getRenderTarget();
    this.renderer.setRenderTarget(this.post.sceneRT);
    const linked = this.renderer.compileAsync(this.scene, this.camera);
    this.renderer.setRenderTarget(prev);
    await linked;
    this.update(0);
    this.render();
  }

  /** an actor of an archetype: its baked sheet when one stands for it (scale, height, variant), else the generated sprite */
  private actor(arch: string, role: string, x: number, z: number, id: number): Actor {
    const m = this.cast?.get(arch);
    const a: Actor = { id, spec: m?.id ?? arch, base: arch, role, detail: role === 'player' ? 'hero' : role === 'crowd' ? 'crowd' : 'mid', pos: new THREE.Vector3(x, 0, z), facing: 'down', dir: 'down', flip: false, anim: 'idle' as Anim, t: (id % 7) * 0.31, speed: 0, tint: [1, 1, 1], scale: m?.scale ?? 1, height: m?.height ?? 1.7, radius: 0.3 };
    const cv = m?.variants;
    if (cv) { const v = variantOf(id, cv.list.length, cv.fixed?.[arch]); if (v > 0) a.variant = { hair: cv.list[v - 1][0], skin: cv.list[v - 1][1], hairRange: cv.hair, skinRange: cv.skin }; }
    return a;
  }

  resize(): void {
    const w = window.innerWidth, h = window.innerHeight, pr = Math.min(window.devicePixelRatio || 1, 2);
    this.post.setSize(w, h, pr);
    this.reflection.setSize(w * pr, h * pr);
    U.uResolution.value.set(this.post.width, this.post.height);
    this.applyCamera(1);
  }

  /** the open space's framing: the pivot follows the hero (held a little toward the square's heart), the camera leans toward the side it
   *  walks to (yaw), comes nearer toward the north wall and rises a little at the square's mouth; every value a smooth function of where the
   *  hero stands, eased (no cut, no blend to author) */
  private applyCamera(k: number): void {
    const p = this.player?.pos ?? new THREE.Vector3(0, 0, -2), x = THREE.MathUtils.clamp(p.x, -9, 9), z = THREE.MathUtils.clamp(p.z, -15, 2);
    const north = THREE.MathUtils.smoothstep(-z, 2, 14);
    const want: CamPose = { yaw: THREE.MathUtils.degToRad(-x * 1.6), pitch: THREE.MathUtils.degToRad(24 - 6 * north), dist: 18 - 4 * north, fov: 40, shift: 0, tx: x * 0.75, ty: 1.3, tz: z * 0.85 - 1.5 };
    const P = this.pose;
    for (const key of ['yaw', 'pitch', 'dist', 'tx', 'ty', 'tz'] as const) P[key] += (want[key] - P[key]) * k;
    applyPose(this.camera, P, window.innerWidth / Math.max(1, window.innerHeight));
  }

  /** the hero walks (arrows or WASD, relative to the camera), the crowd walks its points, the people idle at their spots */
  private walk(dt: number): void {
    const k = this.keys, ix = (k.has('d') || k.has('arrowright') ? 1 : 0) - (k.has('a') || k.has('arrowleft') ? 1 : 0), iz = (k.has('s') || k.has('arrowdown') ? 1 : 0) - (k.has('w') || k.has('arrowup') ? 1 : 0);
    const P = this.player, speed = (this.cast?.get('player')?.walkSpeed ?? 3.2) * (k.has('shift') ? 1.2 : 1);
    if (ix || iz) {
      const yaw = this.pose.yaw, c = Math.cos(yaw), s = Math.sin(yaw), n = Math.hypot(ix, iz);
      const dx = (ix * c + iz * s) / n, dz = (-ix * s + iz * c) / n;
      const [nx, nz] = walkTo(this.place, P.pos.x, P.pos.z, P.pos.x + dx * speed * dt, P.pos.z + dz * speed * dt);
      P.pos.x = nx; P.pos.z = nz;
      P.dir = fiveViewFacing(P.dir, ix, -iz) as Dir; P.flip = ix > 0; P.anim = 'walk' as Anim; P.t += dt;
    } else { P.anim = 'idle' as Anim; P.t += dt; if (P.dir === 'downSide' || P.dir === 'upSide') P.dir = 'side'; }
    for (const a of this.people) {
      a.t += dt;
      const b = a.behaviour; if (!b || b.kind !== 'wander') continue;
      if ((b.wait ?? 0) > 0) { b.wait! -= dt; a.anim = 'idle' as Anim; continue; }
      const tgt = this.place.wander[b.idx ?? 0], dx = tgt[0] - a.pos.x, dz = tgt[1] - a.pos.z, d = Math.hypot(dx, dz), v = (this.cast?.get(a.base ?? '')?.walkSpeed ?? 1.4) * 0.8;
      if (d < 0.3) { b.idx = ((b.idx ?? 0) + 1 + (b.seed % 3)) % this.place.wander.length; b.wait = 1 + ((b.seed + (b.idx ?? 0)) % 5) * 0.6; continue; }
      a.pos.x += (dx / d) * v * dt; a.pos.z += (dz / d) * v * dt; a.anim = 'walk' as Anim;
      a.dir = Math.abs(dx) > Math.abs(dz) * 1.2 ? 'side' : dz > 0 ? 'down' : 'up'; a.flip = dx > 0;
    }
  }

  /** the person the hero stands next to, if any (the play mode's E) */
  nearby(): string | null {
    let best: string | null = null, bd = 2.2 * 2.2;
    for (const a of this.people) { const w = this.who.get(a); if (!w) continue; const d = (a.pos.x - this.player.pos.x) ** 2 + (a.pos.z - this.player.pos.z) ** 2; if (d < bd) { bd = d; best = w; } }
    return best;
  }

  update(dt: number): void {
    this.time = this.frozen ?? this.time + dt;
    U.uTime.value = this.time;
    U.uMoonDir.value.copy(this.keyDir);
    if (dt > 0) this.walk(dt);
    this.applyCamera(dt > 0 ? Math.min(1, dt * 3) : 1);
    const v = this.player.pos.clone().applyMatrix4(this.camera.matrixWorldInverse);
    this.post.params.dofFocus = THREE.MathUtils.clamp(-v.z, 6, 40);
    this.lights.update(this.time, dt, this.camera);
    this.sprites.update([this.player, ...this.people], this.lights, this.camera, this.keyDir, null, this.player);
    this.particles.update(dt, this.time, this.camera, this.post.height, this.lights, null);
  }

  render(): void {
    const r = this.renderer, gpu = this.perf.gpu;
    this.perf.beginFrame();
    r.info.reset();
    gpu.begin('reflection');
    this.reflection.update(r, this.scene, this.camera);
    this.post.render(this.scene, this.camera, this.time, gpu);
    gpu.end(); gpu.poll();
    this.perf.endFrame(r);
    this.frameCount++;
  }

  start(): void {
    const loop = (t: number) => {
      if (this.frameCap.shouldRender(t)) { const now = performance.now(), dt = Math.min(0.05, (now - this.lastT) / 1000); this.lastT = now; this.update(dt); this.render(); }
      requestAnimationFrame(loop);
    };
    this.lastT = performance.now();
    requestAnimationFrame(loop);
  }

  snapshot(): Record<string, unknown> {
    const p = this.perf;
    return {
      kind: this.opts.kind, fps: p.fps, frameMs: p.frameMs, drawCalls: p.drawCalls, triangles: p.triangles, placeTriangles: this.place?.stats.triangles, instances: this.place?.stats.instances,
      buildings: this.place?.stats.buildings, generatorMs: this.buildMs, lights: this.lights.sources.length, people: this.people.length,
      baked: this.people.filter((a) => this.atlas.baked.has(a.spec)).map((a) => a.spec), provisional: this.people.filter((a) => a.spec.startsWith('prov-')).map((a) => a.spec),
      player: { x: +this.player.pos.x.toFixed(2), z: +this.player.pos.z.toFixed(2), spec: this.player.spec }, atlas: `${this.atlas.width}x${this.atlas.height} + baked ${this.atlas.bakedWidth}x${this.atlas.bakedHeight}`,
    };
  }
}
